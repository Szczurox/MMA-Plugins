// One-time setup so `cargo build --release` works in this folder with no environment variables.
//
//   node setup.mjs
//
// The om-file-format C library needs gcc or clang (MSVC cannot compile it), so this project
// builds for the x86_64-pc-windows-gnu target with the MSYS2 mingw64 gcc. Four things need
// arranging, all kept inside this folder (vendor/ and .cargo/ are gitignored):
//
//   1. the Rust gnu target (rustup target add x86_64-pc-windows-gnu)
//   2. the library's C sources as real files (git checks its symlink out as a text file on Windows)
//   3. libclang, which the library's binding generator loads (from the `libclang` pip package)
//   4. .cargo/config.toml pointing at all of the above

import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const vendor = join(here, "vendor");
const TARGET = "x86_64-pc-windows-gnu";
// Must match the om-file-format rev that rust-omfiles pins (see Cargo.lock).
const OM_REV = "d8855e418e2231ae8439f0c7e840fa3f93b371e3";

function run(cmd, args, opts = {}) {
	const r = spawnSync(cmd, args, { encoding: "utf8", shell: false, ...opts });
	return { ok: r.status === 0, out: (r.stdout ?? "").trim(), err: (r.stderr ?? "").trim() };
}
function need(ok, message) {
	if (!ok) {
		console.error(`setup: ${message}`);
		process.exit(1);
	}
}
const fwd = (p) => p.replaceAll("\\", "/");

// 0. Tools that must already exist.
need(run("cargo", ["--version"]).ok, "cargo not found; install Rust from https://rustup.rs");
const gcc = run("gcc", ["--version"]);
need(
	gcc.ok,
	"gcc not found on PATH; install MSYS2 (https://www.msys2.org) and put C:\\msys64\\mingw64\\bin on PATH",
);
console.log(`gcc: ${gcc.out.split("\n")[0]}`);

// 1. The gnu target.
if (!run("rustup", ["target", "list", "--installed"]).out.split("\n").includes(TARGET)) {
	console.log(`adding rust target ${TARGET}`);
	need(run("rustup", ["target", "add", TARGET], { stdio: "inherit" }).ok, "rustup target add failed");
}

// 2. The C sources as real files.
const omDir = join(vendor, "om-file-format");
const sysDir = join(omDir, "rust", "om-file-format-sys");
if (!existsSync(join(sysDir, "c", "src"))) {
	rmSync(omDir, { recursive: true, force: true });
	mkdirSync(vendor, { recursive: true });
	console.log("cloning om-file-format");
	need(
		run("git", ["clone", "--quiet", "https://github.com/open-meteo/om-file-format", omDir]).ok,
		"git clone of om-file-format failed",
	);
	need(run("git", ["-C", omDir, "checkout", "--quiet", OM_REV]).ok, `could not check out ${OM_REV}`);
	// `c` here is a symlink to ../../c; on Windows it is a one-line text file. Replace it.
	rmSync(join(sysDir, "c"), { force: true, recursive: true });
	cpSync(join(omDir, "c"), join(sysDir, "c"), { recursive: true });
}

// 3. libclang.
const libclangDir = join(vendor, "libclang", "clang", "native");
if (!existsSync(join(libclangDir, "libclang.dll"))) {
	console.log("installing libclang (pip, into vendor/)");
	const py = ["python", "py"].find((c) => run(c, ["--version"]).ok);
	need(py, "python not found; needed once to fetch libclang");
	need(
		run(py, ["-m", "pip", "install", "--quiet", "--target", join(vendor, "libclang"), "libclang"], {
			stdio: "inherit",
		}).ok,
		"pip install libclang failed",
	);
	need(existsSync(join(libclangDir, "libclang.dll")), "libclang.dll missing after pip install");
}

// 4. Cargo config.
const gccInclude = run("gcc", ["-print-file-name=include"]).out;
need(existsSync(gccInclude), `gcc include directory not found (${gccInclude})`);
const mingwInclude = join(dirname(dirname(run("gcc", ["-print-prog-name=gcc"]).out)), "include");
const extra = [mingwInclude, gccInclude].filter((p) => existsSync(p)).map((p) => `-I${fwd(p)}`);

mkdirSync(join(here, ".cargo"), { recursive: true });
writeFileSync(
	join(here, ".cargo", "config.toml"),
	`# Generated by setup.mjs for this machine; do not commit.
[build]
target = "${TARGET}"

[env]
CC = "gcc"
LIBCLANG_PATH = { value = "vendor/libclang/clang/native", relative = true }
BINDGEN_EXTRA_CLANG_ARGS = "${extra.join(" ")}"
`,
);
console.log("wrote .cargo/config.toml");
console.log(`\nready: cargo build --release   ->   target/${TARGET}/release/mma-weather-plus.exe`);
